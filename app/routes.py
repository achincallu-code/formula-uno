import ssl
import time
from email.message import EmailMessage
from functools import wraps

import psycopg
from flask import (
    Blueprint,
    current_app,
    flash,
    g,
    redirect,
    render_template,
    request,
    session,
    url_for,
)
from psycopg.rows import dict_row
from werkzeug.security import check_password_hash, generate_password_hash

bp = Blueprint("main", __name__)


def get_db():
    if "db" not in g:
        database_url = current_app.config["DATABASE_URL"]
        if database_url:
            if database_url.startswith("postgres://"):
                database_url = "postgresql://" + database_url.removeprefix("postgres://")
            g.db = psycopg.connect(database_url, row_factory=dict_row)
        else:
            g.db = sqlite3.connect(current_app.config["DATABASE"])
            g.db.row_factory = sqlite3.Row
    return g.db


def execute(query, parameters=()):
    if current_app.config["DATABASE_URL"]:
        query = query.replace("?", "%s")
    return get_db().execute(query, parameters)


def close_db(_error=None):
    database = g.pop("db", None)
    if database is not None:
        database.close()


def init_db():
    database = get_db()
    if current_app.config["DATABASE_URL"]:
        database.execute(
            """
            CREATE TABLE IF NOT EXISTS students (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(80) NOT NULL,
                email VARCHAR(254) NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
            """
        )
    else:
        database.execute(
            """
            CREATE TABLE IF NOT EXISTS students (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
            """
        )
    database.execute(
        """
        CREATE TABLE IF NOT EXISTS password_resets (
            student_id BIGINT NOT NULL UNIQUE,
            token_hash TEXT NOT NULL UNIQUE,
            expires_at BIGINT NOT NULL
        )
        """
    )
    database.commit()


def login_required(view):
    @wraps(view)
    def wrapped_view(**kwargs):
        if "student_id" not in session:
            return redirect(url_for("main.login"))
        return view(**kwargs)

    return wrapped_view


@bp.route("/")
def home():
    if "student_id" in session:
        return redirect(url_for("main.welcome"))
    return redirect(url_for("main.login"))


@bp.route("/iniciar-sesion", methods=("GET", "POST"))
def login():
    if "student_id" in session:
        return redirect(url_for("main.welcome"))

    if request.method == "POST":
        email = request.form.get("email", "").strip().lower()
        password = request.form.get("password", "")
        student = execute(
            "SELECT id, name, email, password_hash FROM students WHERE email = ?",
            (email,),
        ).fetchone()

        if student is None or not check_password_hash(student["password_hash"], password):
            flash("El correo o la contraseña no son correctos.", "error")
        else:
            session.clear()
            session["student_id"] = student["id"]
            session.permanent = request.form.get("remember") == "on"
            return redirect(url_for("main.welcome"))

    return render_template("login.html")


def send_password_reset_email(recipient, reset_url):
    message = EmailMessage()
    message["Subject"] = "Restablece tu contraseña de Aula 306"
    message["From"] = current_app.config["MAIL_FROM"]
    message["To"] = recipient
    message.set_content(
        "Recibimos una solicitud para restablecer tu contraseña.\n\n"
        f"Abre este enlace dentro de una hora:\n{reset_url}\n\n"
        "Si no solicitaste este cambio, puedes ignorar este mensaje."
    )

    host = current_app.config["SMTP_HOST"]
    port = current_app.config["SMTP_PORT"]
    username = current_app.config["SMTP_USERNAME"]
    password = current_app.config["SMTP_PASSWORD"]
    timeout = 15
    if port == 465:
        with smtplib.SMTP_SSL(host, port, timeout=timeout, context=ssl.create_default_context()) as server:
            if username and password:
                server.login(username, password)
            server.send_message(message)
    else:
        with smtplib.SMTP(host, port, timeout=timeout) as server:
            server.starttls(context=ssl.create_default_context())
            if username and password:
                server.login(username, password)
            server.send_message(message)


@bp.route("/recuperar-contrasena", methods=("GET", "POST"))
def forgot_password():
    if request.method == "POST":
        email = request.form.get("email", "").strip().lower()
        if not email or len(email) > 254 or "@" not in email:
            flash("Escribe un correo electrónico válido.", "error")
            return render_template("forgot_password.html")

        if not all(
            (
                current_app.config["SMTP_HOST"],
                current_app.config["MAIL_FROM"],
                current_app.config["PUBLIC_BASE_URL"],
            )
        ):
            current_app.logger.error("Password reset email is not configured.")
            flash("La recuperación por correo aún no está configurada.", "error")
            return render_template("forgot_password.html")

        student = execute(
            "SELECT id, email FROM students WHERE email = ?",
            (email,),
        ).fetchone()
        if student is not None:
            raw_token = secrets.token_urlsafe(32)
            token_hash = hashlib.sha256(raw_token.encode("utf-8")).hexdigest()
            expires_at = int(time.time()) + 3600
            execute("DELETE FROM password_resets WHERE student_id = ?", (student["id"],))
            execute(
                "INSERT INTO password_resets (student_id, token_hash, expires_at) VALUES (?, ?, ?)",
                (student["id"], token_hash, expires_at),
            )
            get_db().commit()
            reset_path = url_for("main.reset_password", token=raw_token)
            reset_url = f'{current_app.config["PUBLIC_BASE_URL"].rstrip("/")}{reset_path}'
            try:
                send_password_reset_email(student["email"], reset_url)
            except (OSError, smtplib.SMTPException):
                current_app.logger.exception("Unable to send password reset email.")
                execute("DELETE FROM password_resets WHERE student_id = ?", (student["id"],))
                get_db().commit()
                flash("No se pudo enviar el correo. Inténtalo de nuevo más tarde.", "error")
                return render_template("forgot_password.html")

        flash("Si el correo está registrado, recibirás un enlace para restablecer tu contraseña.", "success")
        return redirect(url_for("main.forgot_password"))

    return render_template("forgot_password.html")


@bp.route("/restablecer-contrasena/<token>", methods=("GET", "POST"))
def reset_password(token):
    token_hash = hashlib.sha256(token.encode("utf-8")).hexdigest()
    reset = execute(
        "SELECT student_id FROM password_resets WHERE token_hash = ? AND expires_at > ?",
        (token_hash, int(time.time())),
    ).fetchone()
    if reset is None:
        flash("El enlace no es válido o ya venció. Solicita uno nuevo.", "error")
        return redirect(url_for("main.forgot_password"))

    if request.method == "POST":
        password = request.form.get("password", "")
        confirmation = request.form.get("confirmation", "")
        if len(password) < 8:
            flash("Tu contraseña debe tener al menos 8 caracteres.", "error")
        elif password != confirmation:
            flash("Las contraseñas no coinciden.", "error")
        else:
            consumed = execute(
                """
                DELETE FROM password_resets
                WHERE student_id = ? AND token_hash = ? AND expires_at > ?
                """,
                (reset["student_id"], token_hash, int(time.time())),
            )
            if consumed.rowcount != 1:
                flash("El enlace no es válido o ya venció. Solicita uno nuevo.", "error")
                return redirect(url_for("main.forgot_password"))
            execute(
                "UPDATE students SET password_hash = ? WHERE id = ?",
                (generate_password_hash(password), reset["student_id"]),
            )
            get_db().commit()
            flash("Tu contraseña se actualizó. Ya puedes iniciar sesión.", "success")
            return redirect(url_for("main.login"))

    return render_template("reset_password.html")


@bp.route("/crear-cuenta", methods=("GET", "POST"))
def register():
    if "student_id" in session:
        return redirect(url_for("main.welcome"))

    if request.method == "POST":
        name = " ".join(request.form.get("name", "").split())
        email = request.form.get("email", "").strip().lower()
        password = request.form.get("password", "")

        if not name or len(name) > 80:
            flash("Escribe tu nombre (máximo 80 caracteres).", "error")
        elif not email or len(email) > 254 or "@" not in email:
            flash("Escribe un correo electrónico válido.", "error")
        elif len(password) < 8:
            flash("Tu contraseña debe tener al menos 8 caracteres.", "error")
        else:
            try:
                if current_app.config["DATABASE_URL"]:
                    cursor = execute(
                        "INSERT INTO students (name, email, password_hash) VALUES (?, ?, ?) RETURNING id",
                        (name, email, generate_password_hash(password)),
                    )
                    student_id = cursor.fetchone()["id"]
                else:
                    cursor = execute(
                        "INSERT INTO students (name, email, password_hash) VALUES (?, ?, ?)",
                        (name, email, generate_password_hash(password)),
                    )
                    student_id = cursor.lastrowid
                get_db().commit()
            except sqlite3.IntegrityError:
                get_db().rollback()
                flash("Ya existe una cuenta con ese correo. Prueba iniciar sesión.", "error")
            except psycopg.errors.UniqueViolation:
                get_db().rollback()
                flash("Ya existe una cuenta con ese correo. Prueba iniciar sesión.", "error")
            else:
                session.clear()
                session["student_id"] = student_id
                return redirect(url_for("main.welcome"))

    return render_template("register.html")


@bp.route("/bienvenida")
@login_required
def welcome():
    student = execute(
        "SELECT name, email FROM students WHERE id = ?",
        (session["student_id"],),
    ).fetchone()

    if student is None:
        session.clear()
        return redirect(url_for("main.login"))

    return render_template("welcome.html", student=student)


